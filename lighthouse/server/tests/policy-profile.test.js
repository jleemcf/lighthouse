'use strict';
require('../../tests/sandbox.cjs');
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const source = path.resolve(__dirname, '..');
const python = process.platform === 'win32' ? 'python' : 'python3';

function generate(context, args) {
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'lh-policy-profile-'));
  context.after(() => fs.rmSync(scratch, { recursive: true, force: true }));
  const output = path.join(scratch, 'rulings.json');
  const result = spawnSync(python, [path.join(source, 'make-rulings.py'), '--out', output, ...args], {
    encoding: 'utf8',
    env: { ...process.env, PYTHONDONTWRITEBYTECODE: '1' },
  });
  assert.equal(result.status, 0, result.stderr);
  return fs.readFileSync(output, 'utf8');
}

test('compatibility policy profile preserves all bundled records and generated bytes', context => {
  const expected = fs.readFileSync(path.join(source, 'rulings.json'), 'utf8').replaceAll('\r\n', '\n');
  assert.equal(generate(context, []), expected);
  assert.ok(JSON.parse(expected).rulings.every(record => !record.scene && !record.supersededBy));
});

test('custom policy generation uses its own section and explicit metadata only', context => {
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'lh-custom-profile-'));
  context.after(() => fs.rmSync(scratch, { recursive: true, force: true }));
  const input = path.join(scratch, 'policies.md');
  const text = '## Local policies\n8. **Backups.** Keep a copy.\n15. **Recovery.** Restore the copy.\n';
  fs.writeFileSync(input, text);
  const plain = JSON.parse(generate(context, ['--source', input]));
  assert.equal(plain.count, 2);
  assert.ok(plain.rulings.every(record => !record.scene && !record.supersededBy));
  const profile = path.join(scratch, 'profile.json');
  fs.writeFileSync(profile, JSON.stringify({ scene: [8], supersededBy: { 15: [8] } }));
  const custom = JSON.parse(generate(context, ['--source', input, '--profile', profile]));
  assert.equal(custom.rulings[0].scene, true);
  assert.deepEqual(custom.rulings[1].supersededBy, [8]);
});
